-- Module: points
-- user_id belongs to auth: indexed, no foreign key (ADR 0005).

create table points_ledger (
    id         bigint generated by default as identity,
    user_id    uuid        not null,
    amount     integer     not null,
    reason     varchar(24) not null,
    -- e.g. quiz:{quizAttemptId}, streak:{quizAttemptId}; the same award is never written twice
    ref_id     varchar(64) not null,
    -- written by the application from its Clock (not the database default): the daily cap
    -- is computed per calendar day in prescription.timezone, and tests use a fixed clock
    created_at timestamptz not null,
    constraint pk_points_ledger primary key (id),
    constraint uq_points_ledger_ref unique (ref_id),
    constraint ck_points_ledger_amount check (amount > 0),
    constraint ck_points_ledger_reason check (reason in ('QUIZ_CORRECT', 'QUIZ_CORRECT_WEAK', 'STREAK_BONUS'))
);

-- Total and today's points per learner.
create index ix_points_ledger_user_time on points_ledger (user_id, created_at);

-- The learner's streak of consecutive correct answers, owned by points (ADR 0005).
create table points_streak (
    user_id     uuid        not null,
    current     integer     not null default 0,
    best        integer     not null default 0,
    -- the last answer applied; replaying the same answer does not change the streak
    last_ref_id varchar(64),
    version     bigint      not null default 0,
    created_at  timestamptz not null default now(),
    updated_at  timestamptz not null default now(),
    constraint pk_points_streak primary key (user_id),
    constraint ck_points_streak_values check (current >= 0 and best >= current)
);
