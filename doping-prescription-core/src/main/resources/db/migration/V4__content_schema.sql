-- Module: content
-- Seeded ids are written explicitly; identity sequences are moved past them by the seeder (docs/seed-verisi.md).

create table topic (
    id          integer generated by default as identity,
    code        varchar(32)  not null,
    name        varchar(100) not null,
    exam_type   varchar(8)   not null,
    subject     varchar(50)  not null,
    exam_weight numeric(4, 3) not null,
    sort_order  integer      not null,
    created_at  timestamptz  not null default now(),
    updated_at  timestamptz  not null default now(),
    constraint pk_topic primary key (id),
    constraint uq_topic_code unique (code),
    constraint ck_topic_exam_type check (exam_type in ('TYT')),
    constraint ck_topic_exam_weight check (exam_weight between 0 and 1)
);

create table topic_keyword (
    id          integer generated by default as identity,
    topic_id    integer       not null,
    keyword     varchar(100)  not null,
    weight      numeric(3, 2) not null,
    is_negative boolean       not null default false,
    created_at  timestamptz   not null default now(),
    constraint pk_topic_keyword primary key (id),
    constraint fk_topic_keyword_topic foreign key (topic_id) references topic (id),
    -- also serves lookups by topic_id
    constraint uq_topic_keyword unique (topic_id, keyword),
    constraint ck_topic_keyword_weight check (weight between 0 and 1)
);

create table content_item (
    id            integer generated by default as identity,
    title         varchar(150)  not null,
    description   text          not null,
    teacher_name  varchar(100)  not null,
    video_url     varchar(300),
    duration_sec  integer       not null,
    difficulty    smallint      not null,
    content_kind  varchar(16)   not null,
    quality_score numeric(4, 3) not null,
    status        varchar(16)   not null,
    -- null while the video is not published yet (DRAFT / TAGGED)
    published_at  timestamptz,
    created_at    timestamptz   not null default now(),
    updated_at    timestamptz   not null default now(),
    constraint pk_content_item primary key (id),
    constraint ck_content_item_duration check (duration_sec > 0),
    constraint ck_content_item_difficulty check (difficulty between 1 and 5),
    constraint ck_content_item_kind check (content_kind in ('CONCEPT', 'SOLVED_EXAMPLE', 'TIP')),
    constraint ck_content_item_quality check (quality_score between 0 and 1),
    constraint ck_content_item_status check (status in ('DRAFT', 'TAGGED', 'LIVE', 'RETIRED'))
);

-- The feed only reads LIVE videos.
create index ix_content_item_status on content_item (status);

create table content_topic_map (
    content_id  integer       not null,
    topic_id    integer       not null,
    weight      numeric(3, 2) not null,
    tag_source  varchar(16)   not null,
    confidence  numeric(3, 2) not null,
    -- module boundary: users belong to auth, so no foreign key (ADR 0005)
    approved_by uuid,
    approved_at timestamptz,
    created_at  timestamptz   not null default now(),
    updated_at  timestamptz   not null default now(),
    constraint pk_content_topic_map primary key (content_id, topic_id),
    constraint fk_content_topic_map_content foreign key (content_id) references content_item (id),
    constraint fk_content_topic_map_topic foreign key (topic_id) references topic (id),
    constraint ck_content_topic_map_weight check (weight between 0 and 1),
    constraint ck_content_topic_map_confidence check (confidence between 0 and 1),
    constraint ck_content_topic_map_tag_source check (tag_source in ('MANUAL', 'KEYWORD_RULE'))
);

create index ix_content_topic_map_topic on content_topic_map (topic_id);

create table micro_question (
    id          integer generated by default as identity,
    content_id  integer     not null,
    topic_id    integer     not null,
    stem        text        not null,
    options     jsonb       not null,
    -- never returned to students (AGENTS.md rule 5)
    correct_key char(1)     not null,
    explanation text        not null,
    difficulty  smallint    not null,
    status      varchar(16) not null,
    created_at  timestamptz not null default now(),
    updated_at  timestamptz not null default now(),
    constraint pk_micro_question primary key (id),
    constraint fk_micro_question_content foreign key (content_id) references content_item (id),
    constraint fk_micro_question_topic foreign key (topic_id) references topic (id),
    constraint ck_micro_question_correct_key check (correct_key in ('A', 'B', 'C', 'D')),
    constraint ck_micro_question_difficulty check (difficulty between 1 and 5),
    constraint ck_micro_question_status check (status in ('DRAFT', 'LIVE', 'RETIRED'))
);

create index ix_micro_question_content on micro_question (content_id);
create index ix_micro_question_topic on micro_question (topic_id);
