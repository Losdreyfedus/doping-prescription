-- Module: learner
-- user_id and topic_id belong to other modules (auth, content): indexed, no foreign keys (ADR 0005).

-- Append-only signal log; mastery can always be recomputed from it.
-- Production note: partition by occurred_at (monthly range partitions); not needed for the demo.
create table learner_signal (
    id              bigint generated by default as identity,
    user_id         uuid         not null,
    topic_id        integer      not null,
    signal_type     varchar(24)  not null,
    -- attempt id, quiz attempt id or impression id
    source_ref      varchar(64)  not null,
    occurred_at     timestamptz  not null,
    -- e.g. exam:{attemptId}:{questionId}; a replayed event cannot record the same signal twice
    idempotency_key varchar(100) not null,
    created_at      timestamptz  not null default now(),
    constraint pk_learner_signal primary key (id),
    constraint uq_learner_signal_idempotency unique (idempotency_key),
    constraint ck_learner_signal_type check (signal_type in (
        'EXAM_CORRECT', 'EXAM_WRONG', 'EXAM_BLANK', 'QUIZ_CORRECT', 'QUIZ_WRONG', 'VIDEO_COMPLETED', 'VIDEO_SKIPPED'))
);

create index ix_learner_signal_user_topic_time on learner_signal (user_id, topic_id, occurred_at);
create index ix_learner_signal_topic on learner_signal (topic_id);

-- Full-precision mastery per learner and topic (docs/algoritma.md §1); rounded only in API responses.
create table learner_topic_mastery (
    user_id              uuid             not null,
    topic_id             integer          not null,
    mastery              double precision not null,
    confidence           double precision not null,
    attempts             integer          not null default 0,
    correct              integer          not null default 0,
    -- null until the first mastery-affecting signal (a row may exist only because a video was served)
    last_signal_at       timestamptz,
    last_served_at       timestamptz,
    last_exam_attempt_id uuid,
    last_exam_total      smallint,
    last_exam_correct    smallint,
    -- optimistic locking for concurrent signal updates
    version              bigint           not null default 0,
    created_at           timestamptz      not null default now(),
    updated_at           timestamptz      not null default now(),
    constraint pk_learner_topic_mastery primary key (user_id, topic_id),
    constraint ck_learner_topic_mastery_mastery check (mastery between 0 and 1),
    constraint ck_learner_topic_mastery_confidence check (confidence between 0 and 1),
    constraint ck_learner_topic_mastery_counts check (attempts >= 0 and correct between 0 and attempts),
    constraint ck_learner_topic_mastery_last_exam check (last_exam_correct between 0 and last_exam_total)
);

create index ix_learner_topic_mastery_topic on learner_topic_mastery (topic_id);
