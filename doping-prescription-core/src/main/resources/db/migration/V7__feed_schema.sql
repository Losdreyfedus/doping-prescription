-- Module: feed
-- user_id, content_id and target_topic_id belong to other modules: indexed, no foreign keys (ADR 0005).

-- One card shown to a learner, with the numbers behind it for the debug screen.
create table feed_impression (
    id              uuid          not null,
    user_id         uuid          not null,
    session_id      uuid          not null,
    content_id      integer       not null,
    position        smallint      not null,
    pool            varchar(16)   not null,
    target_topic_id integer,
    score           numeric(6, 4) not null,
    score_breakdown jsonb         not null,
    reason_text     varchar(200)  not null,
    algo_version    varchar(16)   not null,
    served_at       timestamptz   not null,
    created_at      timestamptz   not null default now(),
    constraint pk_feed_impression primary key (id),
    constraint ck_feed_impression_position check (position >= 0),
    constraint ck_feed_impression_pool check (pool in ('WEAK_TOPIC', 'REVIEW_DUE', 'EXPLORE', 'POPULAR', 'FALLBACK'))
);

create index ix_feed_impression_user_served on feed_impression (user_id, served_at);
-- Session dedup falls back to this table when Redis is down (docs/algoritma.md §4).
create index ix_feed_impression_session on feed_impression (session_id);
create index ix_feed_impression_content on feed_impression (content_id);
create index ix_feed_impression_topic on feed_impression (target_topic_id);

-- Production note: partition by client_ts (monthly range partitions); not needed for the demo.
create table feed_interaction (
    id              bigint generated by default as identity,
    impression_id   uuid        not null,
    user_id         uuid        not null,
    -- client-generated; a retried batch cannot record the same interaction twice
    client_event_id varchar(64) not null,
    event           varchar(16) not null,
    watch_ms        integer,
    client_ts       timestamptz not null,
    created_at      timestamptz not null default now(),
    constraint pk_feed_interaction primary key (id),
    constraint fk_feed_interaction_impression foreign key (impression_id) references feed_impression (id),
    constraint uq_feed_interaction_client_event unique (client_event_id),
    constraint ck_feed_interaction_event check (event in (
        'VIEW_START', 'VIEW_COMPLETE', 'SKIP', 'LIKE', 'QUIZ_SHOWN', 'QUIZ_DISMISSED')),
    constraint ck_feed_interaction_watch_ms check (watch_ms >= 0)
);

create index ix_feed_interaction_impression on feed_interaction (impression_id);
create index ix_feed_interaction_user_time on feed_interaction (user_id, client_ts);
