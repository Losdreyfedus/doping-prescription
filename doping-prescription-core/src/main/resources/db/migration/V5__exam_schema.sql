-- Module: exam

create table exam (
    id           integer generated by default as identity,
    title        varchar(150) not null,
    exam_type    varchar(8)   not null,
    duration_min integer      not null,
    is_active    boolean      not null default true,
    created_at   timestamptz  not null default now(),
    updated_at   timestamptz  not null default now(),
    constraint pk_exam primary key (id),
    constraint ck_exam_exam_type check (exam_type in ('TYT')),
    constraint ck_exam_duration check (duration_min > 0)
);

create table exam_question (
    id              integer generated by default as identity,
    exam_id         integer     not null,
    order_no        smallint    not null,
    -- module boundary: topics belong to content, so no foreign key (ADR 0005)
    topic_id        integer     not null,
    stem            text        not null,
    options         jsonb       not null,
    -- returned only in the result of a submitted attempt
    correct_key     char(1)     not null,
    explanation     text        not null,
    -- answer given in the demo scenario (null = left blank); admin API and personas only, never sent to students
    scenario_answer char(1),
    difficulty      smallint    not null,
    created_at      timestamptz not null default now(),
    updated_at      timestamptz not null default now(),
    constraint pk_exam_question primary key (id),
    constraint fk_exam_question_exam foreign key (exam_id) references exam (id),
    -- also serves lookups by exam_id
    constraint uq_exam_question_order unique (exam_id, order_no),
    constraint ck_exam_question_order check (order_no > 0),
    constraint ck_exam_question_correct_key check (correct_key in ('A', 'B', 'C', 'D', 'E')),
    constraint ck_exam_question_scenario_answer check (scenario_answer in ('A', 'B', 'C', 'D', 'E')),
    constraint ck_exam_question_difficulty check (difficulty between 1 and 5)
);

create index ix_exam_question_topic on exam_question (topic_id);

create table exam_attempt (
    id            uuid          not null,
    -- module boundary: users belong to auth, so no foreign key (ADR 0005)
    user_id       uuid          not null,
    exam_id       integer       not null,
    status        varchar(16)   not null,
    started_at    timestamptz   not null,
    submitted_at  timestamptz,
    -- filled on submit
    correct_count smallint,
    wrong_count   smallint,
    blank_count   smallint,
    net           numeric(5, 2),
    -- optimistic locking: two concurrent submits of the same attempt cannot both succeed
    version       bigint        not null default 0,
    created_at    timestamptz   not null default now(),
    updated_at    timestamptz   not null default now(),
    constraint pk_exam_attempt primary key (id),
    constraint fk_exam_attempt_exam foreign key (exam_id) references exam (id),
    constraint ck_exam_attempt_status check (status in ('IN_PROGRESS', 'SUBMITTED')),
    constraint ck_exam_attempt_submitted check ((status = 'SUBMITTED') = (submitted_at is not null))
);

create index ix_exam_attempt_user_exam on exam_attempt (user_id, exam_id);
create index ix_exam_attempt_exam on exam_attempt (exam_id);
-- At most one IN_PROGRESS attempt per learner and exam (docs/veri-modeli.md), enforced by the database.
create unique index uq_exam_attempt_in_progress on exam_attempt (user_id, exam_id) where status = 'IN_PROGRESS';

create table exam_answer (
    attempt_id     uuid        not null,
    question_id    integer     not null,
    -- null = left blank
    selected_key   char(1),
    -- filled on submit
    result         varchar(8),
    time_spent_sec integer,
    created_at     timestamptz not null default now(),
    updated_at     timestamptz not null default now(),
    constraint pk_exam_answer primary key (attempt_id, question_id),
    constraint fk_exam_answer_attempt foreign key (attempt_id) references exam_attempt (id),
    constraint fk_exam_answer_question foreign key (question_id) references exam_question (id),
    constraint ck_exam_answer_selected_key check (selected_key in ('A', 'B', 'C', 'D', 'E')),
    constraint ck_exam_answer_result check (result in ('CORRECT', 'WRONG', 'BLANK')),
    constraint ck_exam_answer_time_spent check (time_spent_sec >= 0)
);

create index ix_exam_answer_question on exam_answer (question_id);
