package com.doping.prescription.feed.application;

import com.doping.prescription.feed.api.InteractionRecorded;
import com.doping.prescription.feed.domain.InteractionType;
import com.doping.prescription.feed.domain.ServedCard;
import com.doping.prescription.feed.persistence.FeedImpression;
import com.doping.prescription.feed.persistence.FeedImpressionRepository;
import com.doping.prescription.feed.persistence.FeedQueries;
import com.doping.prescription.feed.persistence.FeedQueries.NewInteraction;
import java.time.Clock;
import java.time.Instant;
import java.util.List;
import java.util.Map;
import java.util.UUID;
import java.util.function.Function;
import java.util.stream.Collectors;
import org.jspecify.annotations.Nullable;
import org.springframework.context.ApplicationEventPublisher;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

/** Records what learners do with cards (docs/api.md, POST /api/feed/interactions). */
@Service
public class InteractionService {

    private final FeedQueries queries;
    private final FeedImpressionRepository impressions;
    private final ApplicationEventPublisher events;
    private final Clock clock;

    InteractionService(
            FeedQueries queries, FeedImpressionRepository impressions, ApplicationEventPublisher events, Clock clock) {
        this.queries = queries;
        this.impressions = impressions;
        this.events = events;
        this.clock = clock;
    }

    /**
     * Stores each new interaction and publishes it. Repeated client event ids and cards of other learners are
     * ignored: a batch is fire-and-forget for the client.
     */
    @Transactional
    public void record(UUID userId, List<Interaction> batch) {
        Map<UUID, FeedImpression> own =
                impressions
                        .findAllById(batch.stream()
                                .map(Interaction::impressionId)
                                .distinct()
                                .toList())
                        .stream()
                        .filter(impression -> impression.getUserId().equals(userId))
                        .collect(Collectors.toMap(FeedImpression::getId, Function.identity()));
        Instant now = clock.instant();
        for (Interaction interaction : batch) {
            FeedImpression impression = own.get(interaction.impressionId());
            if (impression == null) {
                continue;
            }
            boolean stored = queries.recordInteraction(new NewInteraction(
                    interaction.impressionId(),
                    userId,
                    interaction.clientEventId(),
                    interaction.event().name(),
                    interaction.watchMs(),
                    interaction.clientTs()));
            if (stored) {
                ServedCard card = impression.getCard();
                events.publishEvent(new InteractionRecorded(
                        UUID.randomUUID(),
                        InteractionRecorded.SCHEMA_VERSION,
                        now,
                        userId,
                        impression.getId(),
                        card.contentId(),
                        card.targetTopicId(),
                        interaction.event().name(),
                        interaction.watchMs()));
            }
        }
    }

    /**
     * @param clientEventId generated by the web app; a retried batch cannot record the same event twice
     * @param watchMs       real video milliseconds watched (the demo speed factor removed)
     */
    public record Interaction(
            String clientEventId,
            UUID impressionId,
            InteractionType event,
            @Nullable Integer watchMs,
            Instant clientTs) {}
}
